OpenBox.FantasyRegistry.listTournaments = function () {
  return Object.values(OpenBox.FantasyRegistry.tournaments).map(function (t) {
    return {
      id: t.id,
      name: t.name,
      region: t.region,
      type: t.type,
      club_count: (t.clubs || []).length,
      cols: t.cols,
      rows: t.rows,
    };
  });
};

OpenBox.FantasyRegistry.getTournament = function (id) {
  var t = OpenBox.FantasyRegistry.tournaments[id];
  if (!t) return null;
  return {
    id: t.id,
    name: t.name,
    region: t.region,
    type: t.type,
    cols: t.cols,
    rows: t.rows,
    clubs: (t.clubs || []).map(function (c, i) {
      return { id: c.id, name: c.name, col: i };
    }),
  };
};